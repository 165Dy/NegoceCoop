// Fonction pour obtenir une image aléatoire selon la marque et catégorie
export const getProductImage = (brand, category) => {
  const brandImages = brandsImages[brand];
  if (!brandImages) return 'https://images.unsplash.com/photo-1581093458791-9d42e98e3d35?w=400&h=400&fit=crop';
  
  const categoryImages = brandImages[category];
  if (!categoryImages || categoryImages.length === 0) {
    // Si pas d'images pour cette catégorie, prendre une image au hasard de la marque
    const allBrandImages = Object.values(brandImages).flat();
    return allBrandImages[Math.floor(Math.random() * allBrandImages.length)] || 
           'https://images.unsplash.com/photo-1581093458791-9d42e98e3d35?w=400&h=400&fit=crop';
  }
  
  // Retourner une image aléatoire de la catégorie
  return categoryImages[Math.floor(Math.random() * categoryImages.length)];
};

